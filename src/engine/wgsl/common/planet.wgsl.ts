/**
 * Planet helpers shared by engine shaders (plan §4.1 `wgsl/common/planet.wgsl.ts`).
 *
 * - `PLANET_KINDS`: the planet-kind order the terrain material indexes (`planet_kind` 0..3). It equals the game's
 *   `PLANET_TYPES` (`src/game/planet-field.ts`, where `planetType(seed) = PLANET_TYPES[seed & 3]`); the engine never imports
 *   game code, so tests/engine-terrain-wgsl.test.ts pins the two tables together.
 * - `planetNormalModule(source)`: wraps the per-seed analytic planet normal (`fn tmt_planet_normal(p: vec3<f32>) -> vec3<f32>`)
 *   that the facade provides as the scene facet `terrainPlanetWGSL` (generated by `planetNormalWGSL(seed)`, dual-number
 *   derivatives of the same landform expression the collision field uses).
 * - `planetFallbackNormalWgsl`: `tmt_planet_normal(p) = normalize(p)`, used until a facet is provided (engine sandbox).
 * Both modules are named `terrain-planet`, so a shader links exactly one of them.
 */
import type { PlanetDesc } from '../../contracts';
import { makeModule, tsConstCode } from '../module';

export const PLANET_KINDS = Object.freeze(['volcanic', 'dune', 'glacial', 'temperate'] as const);
export type PlanetKind = PlanetDesc['kind'];

/** Index of a planet kind in PLANET_KINDS (the `planet_kind` the terrain material reads). */
export function planetKindIndex(kind: PlanetKind): number {
  const i = PLANET_KINDS.indexOf(kind);
  if (i < 0) throw new Error(`unknown planet kind ${kind}`);
  return i;
}

export const planetKindWgsl = makeModule('planet-kind', tsConstCode(Object.fromEntries(PLANET_KINDS.map((k, i) => [`PLANET_KIND_${k.toUpperCase()}`, i]))));

export const PLANET_NORMAL_MODULE = 'terrain-planet';

/** The per-seed analytic planet normal from the `terrainPlanetWGSL` facet, as a linkable module. */
export function planetNormalModule(source: string) {
  if (!/fn\s+tmt_planet_normal\s*\(/.test(source)) throw new Error('terrainPlanetWGSL must define fn tmt_planet_normal(p: vec3<f32>) -> vec3<f32>');
  return makeModule(PLANET_NORMAL_MODULE, source);
}

export const planetFallbackNormalWgsl = makeModule(PLANET_NORMAL_MODULE, /* wgsl */ `
fn tmt_planet_normal(p: vec3<f32>) -> vec3<f32> { return p / max(length(p), 1e-6); }
`);

/** Stable 32-bit FNV-1a of a WGSL source (pipeline keys for per-seed shaders). */
export function sourceHash(source: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < source.length; i++) { h ^= source.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }
  return h.toString(16).padStart(8, '0');
}
