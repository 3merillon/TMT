/** Bake the game's ammunition into smoothly shaded title sprites.
 * Run: node node_modules/tsx/dist/cli.mjs scripts/build-title-ordnance.ts
 * Mesh normals and material colors are interpolated per pixel. SVG positions
 * cached transparent renders without starting the battle GPU renderer. */
import { readFileSync, writeFileSync } from 'node:fs';
import sharp from 'sharp';
import { projectileMeshes, setWorkshopBomb } from '../src/game/presentation/projectile-models';
import type { MeshDesc } from '../src/engine';

setWorkshopBomb(readFileSync(new URL('../public/game/workshop-bomb.pmb', import.meta.url)));
const models = projectileMeshes();
const view = (x: number, y: number, z: number) => {
  const a = x * Math.cos(.45) - y * Math.sin(.45), b = x * Math.sin(.45) + y * Math.cos(.45);
  return { x: z * .954 - a * .3, y: -b, z: a * .954 + z * .3 };
};
const srgb = (v: number) => Math.round(Math.min(1, v <= .0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - .055) * 255);

async function render(id: string, mesh: MeshDesc, displayWidth: number): Promise<string> {
  const vertices = Array.from({ length: mesh.positions.length / 3 }, (_, i) => ({
    p: view(mesh.positions[i * 3], mesh.positions[i * 3 + 1], mesh.positions[i * 3 + 2]),
    n: view(mesh.normals[i * 3], mesh.normals[i * 3 + 1], mesh.normals[i * 3 + 2]),
    c: Array.from(mesh.partLocal!.slice(i * 3, i * 3 + 3)),
  }));
  const xs = vertices.map(v => v.p.x), ys = vertices.map(v => v.p.y);
  const minX = Math.min(...xs), maxX = Math.max(...xs), minY = Math.min(...ys), maxY = Math.max(...ys);
  const width = 1024, padding = 4, scale = (width - padding * 2) / (maxX - minX);
  const height = Math.ceil((maxY - minY) * scale) + padding * 2;
  for (const v of vertices) { v.p.x = (v.p.x - minX) * scale + padding; v.p.y = (v.p.y - minY) * scale + padding; }
  const rgba = Buffer.alloc(width * height * 4), depth = new Float32Array(width * height).fill(-Infinity);
  for (let i = 0; i < mesh.indices.length; i += 3) {
    const [a, b, c] = [vertices[mesh.indices[i]], vertices[mesh.indices[i + 1]], vertices[mesh.indices[i + 2]]];
    const denominator = (b.p.y - c.p.y) * (a.p.x - c.p.x) + (c.p.x - b.p.x) * (a.p.y - c.p.y);
    if (Math.abs(denominator) < 1e-8) continue;
    const left = Math.max(0, Math.floor(Math.min(a.p.x, b.p.x, c.p.x))), right = Math.min(width - 1, Math.ceil(Math.max(a.p.x, b.p.x, c.p.x)));
    const top = Math.max(0, Math.floor(Math.min(a.p.y, b.p.y, c.p.y))), bottom = Math.min(height - 1, Math.ceil(Math.max(a.p.y, b.p.y, c.p.y)));
    for (let y = top; y <= bottom; y++) for (let x = left; x <= right; x++) {
      const u = ((b.p.y - c.p.y) * (x + .5 - c.p.x) + (c.p.x - b.p.x) * (y + .5 - c.p.y)) / denominator;
      const v = ((c.p.y - a.p.y) * (x + .5 - c.p.x) + (a.p.x - c.p.x) * (y + .5 - c.p.y)) / denominator, w = 1 - u - v;
      if (u < -1e-6 || v < -1e-6 || w < -1e-6) continue;
      const at = y * width + x, z = a.p.z * u + b.p.z * v + c.p.z * w;
      if (z < depth[at]) continue;
      depth[at] = z;
      const nx = a.n.x * u + b.n.x * v + c.n.x * w, ny = a.n.y * u + b.n.y * v + c.n.y * w, nz = a.n.z * u + b.n.z * v + c.n.z * w;
      const length = Math.hypot(nx, ny, nz) || 1;
      const diffuse = Math.max(0, (-.3 * nx - .6 * ny + .74 * nz) / length);
      const specular = Math.max(0, (-.18 * nx - .34 * ny + .92 * nz) / length) ** 32 * .22;
      for (let channel = 0; channel < 3; channel++) {
        const color = a.c[channel] * u + b.c[channel] * v + c.c[channel] * w;
        rgba[at * 4 + channel] = srgb(color * (.42 + diffuse * 1.1) + specular);
      }
      rgba[at * 4 + 3] = 255;
    }
  }
  // Supersampling smooths the silhouette; interpolated normals keep highlights continuous.
  const png = await sharp(rgba, { raw: { width, height, channels: 4 } }).resize({ width: 512 }).png().toBuffer();
  const imageWidth = displayWidth * width / (width - padding * 2), imageHeight = imageWidth * height / width;
  return `<g id="${id}"><image x="${-imageWidth / 2}" y="${-imageHeight / 2}" width="${imageWidth}" height="${imageHeight}" href="data:image/png;base64,${png.toString('base64')}"/></g>`;
}
const sprites = [];
for (const [id, width] of [['nuclear', 46], ['heavy', 42], ['explosive', 38]] as const) sprites.push(await render(id, models[id], width));
const svg = `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Smooth renders of projectileMeshes() and workshop-bomb.pmb; generated by scripts/build-title-ordnance.ts. -->\n${sprites.join('\n')}\n</svg>\n`;
writeFileSync(new URL('../public/brand/tmt-ordnance.svg', import.meta.url), svg);
console.log(`Title ordnance: ${Buffer.byteLength(svg)} bytes, three smoothly shaded game models.`);
